    fn translation_fallback() {
        assert_eq!(t_in(Lang::De, "Save"), "Speichern");
        assert_eq!(
            t_in(Lang::De, "Something untranslated"),
            "Something untranslated"
        );
        assert_eq!(t_in(Lang::En, "Save"), "Save");
    }

